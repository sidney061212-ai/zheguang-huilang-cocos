const point = (x: number, y: number) => ({ x, y });

const source = (
  id: string,
  x: number,
  y: number,
  angle: number,
  color: LightColor,
  intensity = 1,
  beamWidth = 10,
): LightSourceConfig => ({
  id,
  position: point(x, y),
  x,
  y,
  angle,
  color,
  intensity,
  beamWidth,
});

const mirror = (
  id: string,
  x: number,
  y: number,
  angle: number,
  movable = true,
  rotatable = true,
  length = 96,
  reflectivity = 0.92,
): MirrorConfig => ({
  id,
  position: point(x, y),
  x,
  y,
  angle,
  length,
  movable,
  rotatable,
  reflectivity,
});

const prism = (
  id: string,
  x: number,
  y: number,
  angle: number,
  movable = true,
  rotatable = true,
  size = 62,
  dispersionAngle = 12,
  throughput = 0.82,
): PrismConfig => ({
  id,
  position: point(x, y),
  x,
  y,
  angle,
  size,
  movable,
  rotatable,
  dispersion: dispersionAngle,
  dispersionAngle,
  throughput,
});

const target = (
  id: string,
  x: number,
  y: number,
  acceptedColors: LightColor[],
  requiredIntensity: number,
  chargeTime: number,
  required = true,
  radius = 22,
): TargetConfig => ({
  id,
  position: point(x, y),
  x,
  y,
  radius,
  acceptedColors,
  requiredIntensity,
  chargeTime,
  required,
});

const obstacle = (id: string, x: number, y: number, width: number, height: number): ObstacleConfig => ({
  id,
  position: point(x, y),
  x,
  y,
  width,
  height,
});

